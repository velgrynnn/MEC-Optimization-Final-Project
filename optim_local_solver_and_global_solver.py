beta = (1 / r_u) + (C / f_C) + (alpha_k / r_d)

# Balanced offloaded data amount
m = (C * R_bits) / (C + F * beta)

# Knapsack weight and value
w = m * C
v = (m * C) / F

mu_star_Hz = 1 / F
mu_star_GHz_display = 1 / F_GHz

