def solve_relaxed_node(fixed_vars, solver_name="ipopt"):
    """
    Solves one relaxed B&B node.

    fixed_vars example:
    {0: 1, 2: 0}

    means:
    x_1 = 1, x_3 = 0

    Remaining variables are relaxed:
    0 <= x_k <= 1

    Since this is a maximization problem, the relaxed objective is an upper bound.
    IPOPT/MINOS usually solve minimization, so we minimize the negative objective.
    """

    # ------------------------------------------------------------
    # 1. Check whether fixed variables already violate capacity
    # ------------------------------------------------------------

    fixed_capacity = sum(float(w[k]) * fixed_vars[k] for k in fixed_vars)

    if fixed_capacity > float(F_bar) + 1e-6:
        return {
            "status": "infeasible",
            "fixed_vars": fixed_vars,
            "message": "Fixed variables already violate capacity"
        }

    # ------------------------------------------------------------
    # 2. If all variables are fixed, evaluate directly
    #    Do not call IPOPT/MINOS because no relaxation remains.
    # ------------------------------------------------------------

    if len(fixed_vars) == K:
        x_fixed = np.zeros(K)

        for k in range(K):
            x_fixed[k] = fixed_vars[k]

        fixed_obj = float(np.sum(v * x_fixed))
        used_capacity = float(np.sum(w * x_fixed))

        return {
            "status": "ok",
            "fixed_vars": fixed_vars,
            "x_relaxed": x_fixed,
            "relaxed_obj": fixed_obj,
            "used_capacity": used_capacity,
            "termination": "all variables fixed, evaluated directly"
        }

    # ------------------------------------------------------------
    # 3. Otherwise solve relaxed node with IPOPT/MINOS
    # ------------------------------------------------------------

    model = pyo.ConcreteModel()
    model.K = pyo.RangeSet(0, K - 1)

    model.x = pyo.Var(model.K, bounds=(0, 1))

    # Apply branch constraints
    for k, val in fixed_vars.items():
        model.x[k].fix(val)

    # Minimize negative revenue
    model.obj = pyo.Objective(
        expr=-sum(float(v[k]) * model.x[k] for k in users),
        sense=pyo.minimize
    )

    # Capacity constraint
    model.capacity = pyo.Constraint(
        expr=sum(float(w[k]) * model.x[k] for k in users) <= float(F_bar)
    )

    solver = get_solver(solver_name)

    try:
        result = solver.solve(model, tee=False)
    except Exception as e:
        return {
            "status": "solver_error",
            "message": str(e),
            "fixed_vars": fixed_vars
        }

    termination = str(result.solver.termination_condition).lower()

    if "infeasible" in termination:
        return {
            "status": "infeasible",
            "fixed_vars": fixed_vars,
            "termination": termination
        }

    try:
        x_relaxed = np.array([pyo.value(model.x[k]) for k in users], dtype=float)
        relaxed_obj = float(-pyo.value(model.obj))
        used_capacity = float(np.sum(w * x_relaxed))
    except Exception as e:
        return {
            "status": "no_solution",
            "message": str(e),
            "fixed_vars": fixed_vars,
            "termination": termination
        }

    return {
        "status": "ok",
        "fixed_vars": fixed_vars,
        "x_relaxed": x_relaxed,
        "relaxed_obj": relaxed_obj,
        "used_capacity": used_capacity,
        "termination": termination
    }


