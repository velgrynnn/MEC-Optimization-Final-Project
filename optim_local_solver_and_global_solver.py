def is_integer_solution(x_vec, tol=INTEGER_TOL):
    return np.all(np.abs(x_vec - np.round(x_vec)) <= tol)


def choose_fractional_variable(x_vec, fixed_vars, tol=INTEGER_TOL):
    """
    Choose one fractional variable to branch on.
    This version chooses the unfixed variable closest to 0.5.
    """

    best_k = None
    best_score = -1

    for k, x_val in enumerate(x_vec):
        if k in fixed_vars:
            continue

        distance_to_integer = min(abs(x_val), abs(1 - x_val))

        if distance_to_integer > tol:
            score = 1 - abs(x_val - 0.5)

            if score > best_score:
                best_score = score
                best_k = k

    return best_k


def compute_latency(x_star):
    """
    Computes latency after a binary solution x_star is found.
    """

    x_star_np = np.array(x_star, dtype=float)

    l_star = x_star_np * m

    t_loc = ((R_bits - l_star) * C) / F

    t_off = (
        (l_star / r_u)
        + ((l_star * C) / f_C)
        + ((alpha_k * l_star) / r_d)
    )

    t_total = np.maximum(t_loc, t_off)

    t_only_local = (R_bits * C) / F

    avg_latency_pricing = np.mean(t_total)
    avg_latency_only_local = np.mean(t_only_local)

    return {
        "l_star": l_star,
        "t_loc": t_loc,
        "t_off": t_off,
        "t_total": t_total,
        "t_only_local": t_only_local,
        "avg_latency_pricing": avg_latency_pricing,
        "avg_latency_only_local": avg_latency_only_local,
        "latency_reduction": avg_latency_only_local - avg_latency_pricing
    }


def fixed_vars_display(fixed_vars):
    """
    Convert zero-based internal variable index to one-based display index.
    Example:
    {0:1, 2:0} becomes {1:1, 3:0}
    """

    return str({k + 1: val for k, val in fixed_vars.items()})


