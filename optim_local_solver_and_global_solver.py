# ============================================================

def manual_branch_and_bound_with_tolerance(solver_name="ipopt"):
    """
    Manual Branch-and-Bound for maximization with optimality tolerance.

    For maximization:
    - LB = best feasible integer solution found so far
    - UB = best relaxed upper bound among active branches
    - stop early if UB - LB <= OPTIMALITY_TOL
    """

    if not check_solver_available(solver_name):
        raise RuntimeError(
            f"Solver '{solver_name}' is not available. "
            "Install it first or remove it from RUN_SOLVERS."
        )

    start_time = time.perf_counter()

    best_obj = -np.inf
    best_x = None

    node_log = []
    nodes_solved = 0
    nodes_pruned = 0
    relaxed_solver_calls = 0

    terminated_by_tolerance = False
    terminated_by_node_limit = False

    # ------------------------------------------------------------
    # Solve root node first
    # ------------------------------------------------------------

    root_fixed_vars = {}
    root_result = solve_relaxed_node(root_fixed_vars, solver_name=solver_name)
    nodes_solved += 1

    if root_result.get("called_solver", False):
        relaxed_solver_calls += 1

    active_nodes = []

    if root_result["status"] != "ok":
        nodes_pruned += 1

        node_log.append({
            "Node": nodes_solved,
            "Fixed variables": fixed_vars_display(root_fixed_vars),
            "Current LB before": best_obj,
            "Global UB before": None,
            "Relaxed UB": None,
            "Relaxed x": None,
            "Used capacity": None,
            "Current LB after": best_obj,
            "Global UB after": None,
            "Gap after": None,
            "Action": f"Root pruned: {root_result['status']}"
        })

    else:
        x_root = root_result["x_relaxed"]
        root_ub = root_result["relaxed_ub"]
        root_capacity = root_result["used_capacity"]

        if is_integer_solution(x_root):
            x_integer = np.round(x_root).astype(int)
            best_obj = float(np.sum(v * x_integer))
            best_x = x_integer
            nodes_pruned += 1

            node_log.append({
                "Node": nodes_solved,
                "Fixed variables": fixed_vars_display(root_fixed_vars),
                "Current LB before": -np.inf,
                "Global UB before": root_ub,
                "Relaxed UB": root_ub,
                "Relaxed x": np.round(x_root, 6).tolist(),
                "Used capacity": root_capacity,
                "Current LB after": best_obj,
                "Global UB after": best_obj,
                "Gap after": 0.0,
                "Action": "Root integer solution found; solved"
            })

        else:
            # root becomes active
            active_nodes.append({
                "fixed_vars": root_fixed_vars,
                "ub": root_ub,
                "x_relaxed": x_root,
                "used_capacity": root_capacity
            })

            node_log.append({
                "Node": nodes_solved,
                "Fixed variables": fixed_vars_display(root_fixed_vars),
                "Current LB before": -np.inf,
                "Global UB before": root_ub,
                "Relaxed UB": root_ub,
                "Relaxed x": np.round(x_root, 6).tolist(),
                "Used capacity": root_capacity,
                "Current LB after": best_obj,
                "Global UB after": root_ub,
                "Gap after": None,
                "Action": "Root relaxed solution fractional; added as active node"
            })

    # ------------------------------------------------------------
    # Main B&B loop
    # ------------------------------------------------------------

    while len(active_nodes) > 0:

        if nodes_solved >= MAX_NODES:
            terminated_by_node_limit = True
            print("WARNING: Maximum node limit reached.")
            break

        # Current global UB is the largest UB among active nodes
        global_ub_before = max(node["ub"] for node in active_nodes)

        if best_x is not None:
            current_gap_before = global_ub_before - best_obj

            if current_gap_before <= OPTIMALITY_TOL:
                terminated_by_tolerance = True
                break

        # Pick active node with largest UB
        best_node_index = max(
            range(len(active_nodes)),
            key=lambda i: active_nodes[i]["ub"]
        )

        current_node = active_nodes.pop(best_node_index)

        fixed_vars = current_node["fixed_vars"]
        relaxed_ub = current_node["ub"]
        x_relaxed = current_node["x_relaxed"]
        used_capacity = current_node["used_capacity"]

        current_lb_before = best_obj

        # --------------------------------------------------------
        # Bound pruning
        # --------------------------------------------------------

        if best_x is not None and relaxed_ub <= best_obj + BOUND_TOL:
            nodes_pruned += 1

            global_ub_after = (
                max([node["ub"] for node in active_nodes])
                if len(active_nodes) > 0
                else best_obj
            )

            gap_after = (
                global_ub_after - best_obj
                if best_x is not None
                else None
            )

            node_log.append({
                "Node": "active",
                "Fixed variables": fixed_vars_display(fixed_vars),
                "Current LB before": current_lb_before,
                "Global UB before": global_ub_before,
                "Relaxed UB": relaxed_ub,
                "Relaxed x": np.round(x_relaxed, 6).tolist(),
                "Used capacity": used_capacity,
                "Current LB after": best_obj,
                "Global UB after": global_ub_after,
                "Gap after": gap_after,
                "Action": (
                    f"Pruned by bound: UB={relaxed_ub:.6f} "
                    f"<= LB={current_lb_before:.6f}"
                )
            })

            continue

        # --------------------------------------------------------
        # Integer solution
        # --------------------------------------------------------

        if is_integer_solution(x_relaxed):

            x_integer = np.round(x_relaxed).astype(int)
            integer_obj = float(np.sum(v * x_integer))
            integer_capacity = float(np.sum(w * x_integer))

            old_lb = best_obj

            if integer_capacity <= F_bar + 1e-5 and integer_obj > best_obj:
                best_obj = integer_obj
                best_x = x_integer

                action = (
                    f"Integer solution found, LB updated "
                    f"from {old_lb:.6f} to {best_obj:.6f}"
                )
            else:
                action = (
                    f"Integer solution found, LB not improved. "
                    f"Current LB={best_obj:.6f}"
                )

            nodes_pruned += 1

            global_ub_after = (
                max([node["ub"] for node in active_nodes])
                if len(active_nodes) > 0
                else best_obj
            )

            gap_after = (
                global_ub_after - best_obj
                if best_x is not None
                else None
            )

            node_log.append({
                "Node": "active",
                "Fixed variables": fixed_vars_display(fixed_vars),
                "Current LB before": current_lb_before,
                "Global UB before": global_ub_before,
                "Relaxed UB": relaxed_ub,
                "Relaxed x": np.round(x_relaxed, 6).tolist(),
                "Used capacity": used_capacity,
                "Current LB after": best_obj,
                "Global UB after": global_ub_after,
                "Gap after": gap_after,
                "Action": action
            })

            continue

        # --------------------------------------------------------
        # Branch on a fractional variable
        # --------------------------------------------------------

        branch_k = choose_fractional_variable(x_relaxed, fixed_vars)

        if branch_k is None:
            nodes_pruned += 1

            global_ub_after = (
                max([node["ub"] for node in active_nodes])
                if len(active_nodes) > 0
                else best_obj
            )

            gap_after = (
                global_ub_after - best_obj
                if best_x is not None
                else None
            )

            node_log.append({
                "Node": "active",
                "Fixed variables": fixed_vars_display(fixed_vars),
                "Current LB before": current_lb_before,
                "Global UB before": global_ub_before,
                "Relaxed UB": relaxed_ub,
                "Relaxed x": np.round(x_relaxed, 6).tolist(),
                "Used capacity": used_capacity,
                "Current LB after": best_obj,
                "Global UB after": global_ub_after,
                "Gap after": gap_after,
                "Action": "Pruned: no fractional variable found"
            })

            continue

        # Create child branches
        child_fixed_list = []

        left_branch = dict(fixed_vars)
        left_branch[branch_k] = 0
        child_fixed_list.append(left_branch)

        right_branch = dict(fixed_vars)
        right_branch[branch_k] = 1
        child_fixed_list.append(right_branch)

        child_actions = []

        for child_fixed_vars in child_fixed_list:

            child_result = solve_relaxed_node(
                child_fixed_vars,
                solver_name=solver_name
            )

            nodes_solved += 1

            if child_result.get("called_solver", False):
                relaxed_solver_calls += 1

            if child_result["status"] != "ok":
                nodes_pruned += 1
                child_actions.append(
                    f"Child {fixed_vars_display(child_fixed_vars)} pruned: "
                    f"{child_result['status']}"
                )
                continue

            child_x = child_result["x_relaxed"]
            child_ub = child_result["relaxed_ub"]
            child_capacity = child_result["used_capacity"]

            # Bound prune child immediately if possible
            if best_x is not None and child_ub <= best_obj + BOUND_TOL:
                nodes_pruned += 1
                child_actions.append(
                    f"Child {fixed_vars_display(child_fixed_vars)} "
                    f"pruned by bound: UB={child_ub:.6f} <= LB={best_obj:.6f}"
                )
                continue

            # If child is integer, update incumbent if better
            if is_integer_solution(child_x):
                child_integer = np.round(child_x).astype(int)
                child_obj = float(np.sum(v * child_integer))
                child_used_capacity = float(np.sum(w * child_integer))

                if child_used_capacity <= F_bar + 1e-5 and child_obj > best_obj:
                    old_lb = best_obj
                    best_obj = child_obj
                    best_x = child_integer

                    child_actions.append(
                        f"Child {fixed_vars_display(child_fixed_vars)} "
                        f"integer; LB updated from {old_lb:.6f} to {best_obj:.6f}"
                    )
                else:
                    child_actions.append(
                        f"Child {fixed_vars_display(child_fixed_vars)} "
                        f"integer; LB not improved"
                    )

                nodes_pruned += 1
                continue

            # Otherwise, child remains active
            active_nodes.append({
                "fixed_vars": child_fixed_vars,
                "ub": child_ub,
                "x_relaxed": child_x,
                "used_capacity": child_capacity
            })

            child_actions.append(
                f"Child {fixed_vars_display(child_fixed_vars)} added active "
                f"with UB={child_ub:.6f}"
            )

        global_ub_after = (
            max([node["ub"] for node in active_nodes])
            if len(active_nodes) > 0
            else best_obj
        )

        gap_after = (
            global_ub_after - best_obj
            if best_x is not None
            else None
        )

        node_log.append({
            "Node": "active",
            "Fixed variables": fixed_vars_display(fixed_vars),
            "Current LB before": current_lb_before,
            "Global UB before": global_ub_before,
            "Relaxed UB": relaxed_ub,
            "Relaxed x": np.round(x_relaxed, 6).tolist(),
            "Used capacity": used_capacity,
            "Current LB after": best_obj,
            "Global UB after": global_ub_after,
            "Gap after": gap_after,
            "Action": (
                f"Branch on x_{branch_k + 1}. "
                + " | ".join(child_actions)
            )
        })

    # ------------------------------------------------------------
    # Finalize result
    # ------------------------------------------------------------

    end_time = time.perf_counter()
    wall_time = end_time - start_time

    completed_tree = (len(active_nodes) == 0) and (not terminated_by_node_limit)

    if best_x is None:
        selected_users = []
        used_capacity_best = None
        recovered_prices = []
        latency_results = None
        final_gap = None
        status = "no feasible integer solution"

    else:
        selected_users = [k + 1 for k in users if best_x[k] == 1]
        used_capacity_best = float(np.sum(w * best_x))

        recovered_prices = []

        for k in users:
            if best_x[k] == 1:
                recovered_prices.append(mu_star_GHz_display[k])
            else:
                recovered_prices.append("sufficiently high")

        latency_results = compute_latency(best_x)

        if len(active_nodes) > 0:
            final_global_ub = max(node["ub"] for node in active_nodes)
            final_gap = final_global_ub - best_obj
        else:
            final_global_ub = best_obj
            final_gap = 0.0

        if terminated_by_tolerance:
            status = "stopped by optimality tolerance"
        elif completed_tree:
            status = "completed / proven optimal"
        elif terminated_by_node_limit:
            status = "stopped by node limit"
        else:
            status = "stopped"

    return {
        "solver_name": solver_name,
        "best_x": best_x,
        "best_obj": best_obj,
        "selected_users": selected_users,
        "used_capacity": used_capacity_best,
        "recovered_prices": recovered_prices,
        "nodes_solved": nodes_solved,
        "nodes_pruned": nodes_pruned,
        "relaxed_solver_calls": relaxed_solver_calls,
        "wall_time": wall_time,
        "node_log": pd.DataFrame(node_log),
        "latency_results": latency_results,
        "optimality_gap": final_gap,
        "status": status,
        "terminated_by_tolerance": terminated_by_tolerance,
        "optimality_tolerance": OPTIMALITY_TOL
    }


